namespace Seed.Input
{
    /// <summary>
    /// 「今の生の入力状態」を1回読む器。入力基盤のデバイス依存部分をこの1メソッドに閉じ込める。
    ///
    /// 抽象を挟む理由:
    /// - テスト … 偽実装（FakeInputReader）でスナップショットを差し込めば、
    ///   Unityの実行ループもデバイスも無しに純C#の NUnit EditMode で検証できる
    /// - リプレイ … 記録したスナップショット列を順に返す実装に差し替えるだけで再生になる
    /// - リモート/AI … ネットワーク越しの入力や自動操作も「読み取り実装の一種」に収まる
    ///
    /// 実装は「読むだけ」に徹し、この入力が攻撃なのかガードなのかという意味づけはしない
    /// （意味づけはアプリの方針。基盤は無方針の道具に徹する規約に従う）。
    /// </summary>
    public interface IInputReader
    {
        /// <summary>現在の入力状態を1フレームぶんの写しとして返す（副作用なしで何度呼んでも安全なこと）。</summary>
        InputSnapshot Read();
    }
}
