namespace Seed.Core.Presenter
{
    /// <summary>
    /// 順次再生キューの1ステップ（＝1レコード分の演出）。
    /// Tick は毎フレーム呼ばれ、完了したら true を返す。
    /// コルーチン・Tween・Timeline など任意の再生手段をこの形に包んで使う。
    ///
    /// [設計理由: Complete と Remainder を契約に含める]
    /// - Complete: スキップは「演出を捨てる」だけでは足りない。ガードポーズのように
    ///   「開始で入り、終了で戻す」演出は、途中で捨てると入ったまま固まる。
    ///   終端状態の適用だけは必ず走らせる口を契約に置くことで、スキップ後の画面が嘘をつかない。
    /// - Remainder: 完了時に使い切らなかった時間を報告させる。これがないと
    ///   キューは1フレーム1ステップしか進められず（倍速が効かない）、
    ///   逆に丸ごと持ち越すと実時間より速く進んでしまう（倍速の意味が壊れる）。
    /// </summary>
    public interface IPlaybackStep
    {
        /// <param name="deltaSeconds">経過時間（倍速適用済み）</param>
        /// <returns>true = このステップは完了</returns>
        bool Tick(float deltaSeconds);

        /// <summary>
        /// 残り時間を捨て、終端状態だけを適用して即座に完了する（スキップ用）。
        /// まだ開始していないステップに対して呼ばれることもあるので、
        /// 実装は「開始処理→終端処理」の順で辻褄を合わせること。
        /// 二重呼び出し・完了後の呼び出しは何もしない（冪等）のが契約。
        /// </summary>
        void Complete();

        /// <summary>
        /// 直前の Tick で完了した際、使い切らずに余った時間（秒／0以上）。
        /// キューがこれを次ステップへ持ち越すことで、1フレームに複数ステップを
        /// 「実時間ぶんだけ」消化できる。未完了時・不明な場合は 0 を返してよい。
        /// </summary>
        float Remainder { get; }
    }
}
